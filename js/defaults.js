// ============================================================
// Стартовый набор карточек
// Нужен, чтобы приложением можно было пользоваться с первой минуты.
// Родители потом заменят эмодзи на фото настоящих вещей ребёнка.
// ============================================================

const STARTER = [
  ['🙋', 'Я хочу'],
  ['✅', 'Да'],
  ['❌', 'Нет'],
  ['✋', 'Стоп'],
  ['🥤', 'Пить'],
  ['🍽️', 'Есть'],
  ['🚽', 'Туалет'],
  ['🤕', 'Больно'],
  ['🆘', 'Помоги'],
  ['🧸', 'Играть'],
  ['🌳', 'Гулять'],
  ['🛏️', 'Спать'],
];

export function starterCards() {
  return STARTER.map(([emoji, label], index) => ({
    id: 'starter-' + index,
    label,
    emoji,
    order: index,
  }));
}
